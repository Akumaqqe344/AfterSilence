"""Refresh a separate, backed-up set of generated Obsidian notes from Git and QA evidence."""
from argparse import ArgumentParser
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
from tempfile import NamedTemporaryFile
import json
import re
import subprocess

from vault_sections import TASKS

MARKER = "<!-- generated by After Silence vault sync -->"


def git(repo, *arguments):
    return subprocess.run(["git", "-c", "core.quotepath=false", "-C", str(repo), *arguments],
                          check=True, capture_output=True, text=True, encoding="utf-8").stdout.strip()


def page(ident, heading, body, **properties):
    props = {"id": ident, "tags": ["generated"], **properties}
    header = "\n".join(f"{key}: {json.dumps(value,ensure_ascii=False)}" for key,value in props.items())
    return f"---\n{header}\n---\n{MARKER}\n# {heading}\n\n{body.rstrip()}\n"


def digest(target):
    return sha256(target.read_bytes()).hexdigest() if target.is_file() else None


def qa_snapshot(filename, head):
    if filename is None: return {}, "Проверки для этого снимка не переданы."
    data = json.loads(filename.read_text(encoding="utf-8"))
    if data.get("commit") != head:
        return {}, "Идентификатор проверки относится к другому коммиту."
    result = {}
    for key, row in data["suites"].items():
        report = (filename.parent / row["report"]).resolve()
        if not report.is_relative_to(filename.parent.resolve()):
            raise ValueError(f"QA report must be beside the manifest: {key}")
        passed, failed = row["passed"], row["failed"]
        if any(type(value) is not int or value < 0 for value in (passed,failed)):
            raise ValueError(f"Invalid checks for {key}")
        if digest(report) != row["sha256"]:
            raise ValueError(f"QA report checksum differs for {key}")
        result[key] = {"passed":passed,"failed":failed,"summary":row["summary"]}
    return result, "Результаты относятся к текущему коммиту и прошли проверку контрольных сумм."


def code_records(vault, changed):
    lines = []
    for path in sorted(vault.rglob("*.md")):
        if not path.is_relative_to(vault) or any(segment.startswith("_") or segment.startswith(".") for segment in path.relative_to(vault).parts):
            continue
        text = path.read_text(encoding="utf-8-sig")
        record = re.search(r"^sources: (\[.*\])$",text,re.MULTILINE)
        if record is None: continue
        try: sources = json.loads(record.group(1))
        except json.JSONDecodeError: continue
        if not sources: continue
        touched = [name for name in sources if name in changed]
        relative = path.relative_to(vault).with_suffix("").as_posix()
        lines.append(f"- [[{relative}|{path.stem}]] · " + ", ".join(f"`{name}`" for name in sources) +
                     (" · изменилось " + ", ".join(f"`{name}`" for name in touched) if touched else ""))
    return "\n".join(lines)


def plan(repo, vault, evidence):
    if not (vault / "00 Главная/Dashboard.md").is_file(): raise ValueError("Not an After Silence vault")
    head = git(repo,"rev-parse","HEAD")
    branch = git(repo,"branch","--show-current")
    changes = git(repo,"diff","--name-only","HEAD","--").splitlines() + git(repo,"ls-files","--others","--exclude-standard").splitlines()
    state_target = vault / "_Generated/.state.json"
    previous = json.loads(state_target.read_text(encoding="utf-8")) if state_target.exists() else {}
    old_head = previous.get("commit")
    last = git(repo,"log","-5","--format=%h %s").splitlines()
    if old_head and old_head != head:
        ancestor = subprocess.run(["git","-C",str(repo),"merge-base","--is-ancestor",old_head,head],capture_output=True)
        if ancestor.returncode == 0: changes += git(repo,"diff","--name-only",old_head,head).splitlines()
    changed = set(changes)
    rows, reason = qa_snapshot(evidence,head)
    if evidence is None and previous.get("commit") == head and not changed and previous.get("evidence"):
        rows = previous["evidence"]
        reason = "Проверенные результаты для этого коммита сохранены."
    if changed and git(repo,"status","--porcelain"):
        reason += " В рабочем дереве есть незакоммиченные изменения."
        rows = {}
    status = {key: ("Проверено" if suite in rows and rows[suite]["passed"] > 0 and rows[suite]["failed"] == 0
                   else "Провал" if suite in rows and rows[suite]["failed"] else "Ожидает проверки")
              for key,(_,_,_,_,suite,_) in TASKS.items()}
    verified = sum(value == "Проверено" for value in status.values())
    version = re.search(r'config/version="([^"]+)"',(repo/"project.godot").read_text(encoding="utf-8-sig")).group(1)
    pending = [f"- [[{key}|{TASKS[key][0]}]] · {status[key]}" for key in TASKS if status[key]!="Проверено"]
    table = ["| Набор | Прошли | Сбои | Наблюдение |","| --- | ---: | ---: | --- |"]
    for key,row in rows.items():
        table.append(f"| {key} | {row['passed']} | {row['failed']} | {row['summary'].replace('|','/')} |")
    all_changed = sorted(changed) if changed else previous.get("last_changed", []) if old_head==head else []
    entry = f"## {head[:8]} · {branch}\n\n" + "\n".join(f"- `{name}`" for name in all_changed[:80])
    history = previous.get("history", [])
    if not history or history[0].splitlines()[0] != entry.splitlines()[0]: history = [entry]+history[:19]
    else: history = [entry]+history[1:]
    pages = {
        "Состояние релиза.md":page("release-snapshot","Состояние релиза",
            f"**Версия** — {version}\n\n**Ветка** — `{branch}` · `{head[:8]}`\n\n**Проверено** — {verified} из {len(TASKS)} критериев.\n\n"
            + "\n".join(pending)+"\n\n[[Проверки сборки]] · [[Журнал синхронизации]]"),
        "Проверки сборки.md":page("qa-snapshot","Проверки сборки",reason+"\n\n"+
            ("\n".join(table)+"\n\n" if rows else "")+"[[QA Dashboard]] · [[Совместимость сохранений]]"),
        "Карта исходников.md":page("source-index","Карта исходников","Подтверждённые ссылки из YAML свойств заметок.\n\n"+code_records(vault,set(all_changed))),
        "Журнал синхронизации.md":page("sync-log","Журнал синхронизации","## Последние коммиты\n\n"+
            "\n".join(f"- `{item}`" for item in last)+"\n\n"+"\n\n".join(history)+"\n\n[[Dashboard]]"),
    }
    for key,(name,priority,system,criteria,suite,source) in TASKS.items():
        current = status[key]
        detail = rows[suite]["summary"] if suite in rows else "Доказательство для текущей сборки ожидается."
        pages[f"Статус {key}.md"] = page("status-"+key,name,
            f"[[{key}|Карточка задачи]]\n\n**Критерий** — {criteria}\n\n**Проверка** — {detail}\n\n**Источник** — `{source}`.",
            task_id=key, status=current, priority=priority, system=system, title=name, build=head[:8])
    managed_hashes = {name:sha256(content.encode("utf-8")).hexdigest() for name,content in pages.items()}
    pages[".state.json"] = json.dumps({"commit":head,"last_changed":all_changed,"history":history,"evidence":rows,"managed_hashes":managed_hashes}, ensure_ascii=False,indent=2)+"\n"
    return pages


def atomic_write(target, content):
    target.parent.mkdir(parents=True,exist_ok=True)
    try:
        with NamedTemporaryFile(dir=target.parent,prefix=".sync-",delete=False) as stream:
            temp = Path(stream.name)
            stream.write(content)
            stream.flush()
            import os
            os.fsync(stream.fileno())
        temp.replace(target)
    finally:
        if "temp" in locals() and temp.exists(): temp.unlink()


def synchronize(repo, vault, evidence, apply=False):
    pages = plan(repo,vault,evidence)
    generated = vault / "_Generated"
    if generated.resolve().parent != vault.resolve():
        raise ValueError("Generated directory escapes the vault")
    if generated.exists():
        for target in generated.iterdir():
            if target.is_symlink() or target.resolve().parent != generated.resolve():
                raise ValueError("Generated path is redirected")
    state_path = generated / ".state.json"
    previous = json.loads(state_path.read_text(encoding="utf-8")) if state_path.is_file() else {}
    managed_hashes = previous.get("managed_hashes",{})
    pending = {}
    for name,content in pages.items():
        target = generated / name
        old = target.read_bytes() if target.is_file() else None
        new = content.encode("utf-8")
        if old == new: continue
        if old and target.suffix==".md":
            if MARKER.encode() not in old:
                raise ValueError(f"Manual file in generated area: {target.name}")
            if name in managed_hashes and sha256(old).hexdigest() != managed_hashes[name]:
                raise ValueError(f"Manual edit retained: {target.name}")
        pending[target] = (old,new)
    if not apply or not pending:
        return {"mode":"preview" if not apply else "apply","files":[target.name for target in pending],"writes":0}
    generated.mkdir(parents=True,exist_ok=True)
    lock = generated / ".sync.lock"
    with lock.open("x",encoding="utf-8") as marker:
        marker.write("After Silence vault sync")
    try:
        time = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
        backup = vault / "_SyncBackups" / time
        if not backup.resolve().is_relative_to(vault.resolve()):
            raise ValueError("Backup directory escapes the vault")
        for path,(old,_) in pending.items():
            if (path.read_bytes() if path.is_file() else None) != old:
                raise ValueError(f"Concurrent change: {path.name}")
            if old is not None: atomic_write(backup / path.name,old)
        for path,(_,new) in pending.items(): atomic_write(path,new)
    finally:
        lock.unlink()
    return {"mode":"apply","files":[target.name for target in pending],"writes":len(pending)}


def main():
    parser=ArgumentParser(description=__doc__)
    parser.add_argument("--repo",type=Path,required=True)
    parser.add_argument("--vault",type=Path,required=True)
    parser.add_argument("--evidence",type=Path)
    parser.add_argument("--apply",action="store_true",help="Write generated notes with backups. Default is a dry run.")
    args=parser.parse_args()
    result=synchronize(args.repo.resolve(),args.vault.resolve(),args.evidence.resolve() if args.evidence else None,args.apply)
    print(json.dumps(result,ensure_ascii=False))


if __name__=="__main__": main()
